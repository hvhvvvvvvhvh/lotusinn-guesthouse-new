-- Additive migration: retain original documents as a pre-migration snapshot.
begin;
create table if not exists public.lotus_schema_versions (key text primary key, applied_at timestamptz not null default now());
alter table public.lotus_schema_versions enable row level security;
revoke all on public.lotus_schema_versions from public,anon,authenticated;
grant select on public.lotus_schema_versions to service_role;
create table if not exists public.lotus_records (
  dataset text not null check (dataset in ('bookings','messages','expenses','blogs','authors')),
  id text not null,
  data jsonb not null check (jsonb_typeof(data) = 'object'),
  search_text text generated always as (lower(coalesce(data->>'title','')||' '||coalesce(data->>'name','')||' '||coalesce(data->>'fullName','')||' '||coalesce(data->>'email','')||' '||coalesce(data->>'phone','')||' '||coalesce(data->>'subject','')||' '||coalesce(data->>'category','')||' '||coalesce(data->>'roomType',''))) stored,
  position bigint generated by default as identity,
  version bigint not null default 1,
  primary key (dataset, id)
);
alter table public.lotus_records enable row level security;
revoke all on public.lotus_records from public, anon, authenticated;
grant select, insert, update, delete on public.lotus_records to service_role;
grant usage, select on sequence public.lotus_records_position_seq to service_role;
create index if not exists lotus_records_order on public.lotus_records (dataset, position desc);
create unique index if not exists lotus_records_slug on public.lotus_records (dataset, (data->>'slug')) where dataset in ('blogs','authors');
create index if not exists lotus_records_author on public.lotus_records ((data->>'authorId')) where dataset='blogs';
create index if not exists lotus_records_status on public.lotus_records (dataset, (data->>'status'));

insert into public.lotus_records(dataset,id,data,position)
select d.key, item.value->>'id', item.value, -item.ordinality
from public.lotus_documents d
cross join lateral jsonb_array_elements(d.data->d.key) with ordinality item(value,ordinality)
where d.key in ('bookings','messages','expenses','blogs','authors')
  and not exists (select 1 from public.lotus_schema_versions where key='records-v1')
on conflict (dataset,id) do nothing;

-- Keep row storage current while the previous deployment is still serving requests.
create or replace function public.lotus_sync_legacy_document() returns trigger
language plpgsql security invoker set search_path='' as $$
begin
  if new.key in ('bookings','messages','expenses','blogs','authors') then
    delete from public.lotus_records r where r.dataset=new.key
      and not exists (select 1 from jsonb_array_elements(new.data->new.key) item where item->>'id'=r.id);
    insert into public.lotus_records(dataset,id,data,position)
      select new.key,item.value->>'id',item.value,-item.ordinality
      from jsonb_array_elements(new.data->new.key) with ordinality item(value,ordinality)
      on conflict(dataset,id) do update set data=excluded.data,position=excluded.position,version=public.lotus_records.version+1;
  end if;
  return new;
end $$;
drop trigger if exists lotus_sync_legacy on public.lotus_documents;
create trigger lotus_sync_legacy after insert or update on public.lotus_documents
for each row execute function public.lotus_sync_legacy_document();

create or replace function public.lotus_mutate_record(p_dataset text,p_id text,p_operation text,p_data jsonb default '{}',p_version bigint default null)
returns jsonb language plpgsql security invoker set search_path='' as $$
declare current_row public.lotus_records; next_row public.lotus_records; next_data jsonb;
begin
  if p_dataset not in ('bookings','messages','expenses','blogs','authors') or p_operation not in ('insert','upsert','patch','delete') then
    raise sqlstate 'PT400' using message='Invalid record operation';
  end if;
  select * into current_row from public.lotus_records where dataset=p_dataset and id=p_id for update;
  if p_version is not null and (current_row.id is null or current_row.version<>p_version) then
    raise sqlstate 'PT409' using message='This record changed. Refresh before saving.';
  end if;
  if p_operation='insert' and current_row.id is not null then
    raise sqlstate 'PT409' using message='Record already exists';
  end if;
  if p_operation='delete' then
    delete from public.lotus_records where dataset=p_dataset and id=p_id;
    return jsonb_build_object('record',null,'previous',current_row.data);
  end if;
  if p_operation='patch' and current_row.id is null then
    raise sqlstate 'PT404' using message='Record not found';
  end if;
  next_data := (case when p_operation='patch' then coalesce(current_row.data,'{}')||p_data else p_data end)||jsonb_build_object('id',p_id);
  if current_row.data ? 'createdAt' then next_data := next_data||jsonb_build_object('createdAt',current_row.data->'createdAt'); end if;
  insert into public.lotus_records(dataset,id,data) values(p_dataset,p_id,next_data)
    on conflict(dataset,id) do update set data=excluded.data,version=public.lotus_records.version+1
    returning * into next_row;
  return jsonb_build_object('record',next_row.data,'previous',current_row.data,'version',next_row.version);
end $$;

create or replace function public.lotus_admin_totals(p_dataset text,p_today text)
returns jsonb language sql stable security invoker set search_path='' as $$
select case p_dataset
when 'expenses' then (
 select jsonb_build_object('total',coalesce(sum((data->>'amount')::numeric),0),
   'kitchen',coalesce(sum((data->>'amount')::numeric) filter(where data->>'category'='Kitchen'),0),
   'fuel',coalesce(sum((data->>'amount')::numeric) filter(where data->>'category'='Fuel'),0),
   'staff',coalesce(sum((data->>'amount')::numeric) filter(where data->>'category'='Staff'),0)) from public.lotus_records where dataset='expenses')
when 'authors' then (
 select coalesce(jsonb_object_agg(author_id,total),'{}') from (
   select data->>'authorId' author_id,count(*) total from public.lotus_records where dataset='blogs' and data->>'authorId' is not null group by data->>'authorId'
 ) counts)
when 'dashboard' then jsonb_build_object(
 'totalRooms',(select jsonb_array_length(data#>'{roomsPage,availableRooms}') from public.lotus_documents where key='rooms'),
 'activeBookings',(select count(*) from public.lotus_records where dataset='bookings'),
 'totalMessages',(select count(*) from public.lotus_records where dataset='messages'),
 'publishedBlogs',(select count(*) from public.lotus_records where dataset='blogs' and data->>'status'='Published'),
 'pendingBookings',(select count(*) from public.lotus_records where dataset='bookings' and coalesce(data->>'status','Pending')='Pending'),
 'monthlyIncome',(select coalesce(sum(case when data->>'amount' is not null then (data->>'amount')::numeric else
   coalesce(nullif(regexp_replace(coalesce(data->>'roomPrice',''),'[^0-9.]','','g'),''),'0')::numeric *
   greatest(0,(data->>'checkOut')::date-(data->>'checkIn')::date) end),0)
   from public.lotus_records where dataset='bookings' and coalesce(data->>'status','') not in ('Cancelled','No Show')),
 'year',left(p_today,4),
 'monthly',(select jsonb_agg(jsonb_build_object('label',to_char(make_date(left(p_today,4)::int,m,1),'Mon'),
   'count',(select count(*) from public.lotus_records where dataset='bookings' and left(data->>'checkIn',7)=left(p_today,4)||'-'||lpad(m::text,2,'0')))) from generate_series(1,12) m)
)
else '{}'::jsonb end;
$$;
revoke all on function public.lotus_mutate_record(text,text,text,jsonb,bigint) from public,anon,authenticated;
revoke all on function public.lotus_admin_totals(text,text) from public,anon,authenticated;
revoke all on function public.lotus_sync_legacy_document() from public,anon,authenticated;
grant execute on function public.lotus_mutate_record(text,text,text,jsonb,bigint) to service_role;
grant execute on function public.lotus_admin_totals(text,text) to service_role;
notify pgrst,'reload schema';
insert into public.lotus_schema_versions(key) values('records-v1') on conflict do nothing;
commit;
